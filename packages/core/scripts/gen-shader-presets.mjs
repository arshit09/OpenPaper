// Regenerates src/shaders/presets.generated.ts from @paper-design/shaders-react.
// Run after bumping the shader packages:  node packages/core/scripts/gen-shader-presets.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkgJson = JSON.parse(readFileSync(join(here, '../../../node_modules/@paper-design/shaders-react/package.json'), 'utf8'));
const lib = await import('@paper-design/shaders-react');

const presets = {};
for (const key of Object.keys(lib).filter((k) => k.endsWith('Presets')).sort()) {
  const name = key[0].toUpperCase() + key.slice(1, -'Presets'.length);
  presets[name] = lib[key].map((p) => ({ name: p.name, params: p.params }));
}

const out = `// GENERATED by packages/core/scripts/gen-shader-presets.mjs — do not edit by hand.
// Preset values from @paper-design/shaders-react ${pkgJson.version} (Apache-2.0, Copyright 2026 Paper).
// See THIRD_PARTY_NOTICES.md.

export const SHADER_LIBRARY_VERSION = '${pkgJson.version}';

export type ShaderPresetValue = number | string | boolean | string[];

export interface ShaderPreset {
  name: string;
  params: Record<string, ShaderPresetValue>;
}

export const SHADER_PRESETS: Record<string, ShaderPreset[]> = {
${Object.entries(presets)
  .map(([name, list]) => `  ${name}: [\n${list.map((p) => `    ${JSON.stringify(p)},`).join('\n')}\n  ],`)
  .join('\n')}
};
`;
writeFileSync(join(here, '../src/shaders/presets.generated.ts'), out);
console.log(`wrote ${Object.keys(presets).length} shader preset lists (library ${pkgJson.version})`);
